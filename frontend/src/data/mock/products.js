const generateVariants = (productId, availableColors, availableSizes) => {
  const variants = []
  let variantId = productId * 100
  availableColors.forEach(colorId => {
    availableSizes.forEach(size => {
      variants.push({
        id: variantId++,
        productId,
        colorId,
        size,
        stock: Math.floor(Math.random() * 20) + 1,
        price: null, // same as product price
      })
    })
  })
  return variants
}

